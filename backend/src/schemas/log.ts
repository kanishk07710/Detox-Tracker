/**
 * schemas/log.ts — Zod schemas + shared types for activity logs.
 *
 * Single source of truth: the TypeScript types are DERIVED from the schemas
 * (z.infer), so validation rules and types cannot disagree.
 */

import { z } from 'zod';

export const ACTIVITIES = ['SOCIAL_MEDIA', 'CODING', 'STUDY', 'EXERCISE', 'OTHER'] as const;
export const activitySchema = z.enum(ACTIVITIES);
export type Activity = z.infer<typeof activitySchema>;

// POST /api/logs body.
export const createLogSchema = z.object({
  activity: activitySchema,
  // int() rejects 1.5; the range stops 0, negatives and more-than-a-day entries.
  minutes: z.number().int().min(1).max(1440),
  note: z.string().max(280).optional(),
  // ISO 8601 string; defaults to "now" in the service when omitted.
  loggedAt: z.string().datetime({ offset: true }).optional(),
});
export type CreateLogInput = z.infer<typeof createLogSchema>;

// GET /api/logs query. Both bounds optional ISO dates; from must not be after to.
export const listLogsQuerySchema = z
  .object({
    from: z.string().datetime({ offset: true }).optional(),
    to: z.string().datetime({ offset: true }).optional(),
  })
  .refine((q) => !q.from || !q.to || new Date(q.from) <= new Date(q.to), {
    message: '"from" must not be after "to"',
    path: ['from'],
  });
export type ListLogsQuery = z.infer<typeof listLogsQuerySchema>;

// The stored shape (real Dates internally, ISO strings on the wire).
export interface Log {
  id: string;
  userId: string;
  activity: Activity;
  minutes: number;
  note: string | null;
  loggedAt: Date;
  createdAt: Date;
}

// What the repository needs to create a log (id/createdAt are generated by it).
export interface NewLog {
  activity: Activity;
  minutes: number;
  note: string | null;
  loggedAt: Date;
}
